def 读卡(基: str) -> dict:
    出 = {}
    if not os.path.isdir(基):
        return 出
    for d in sorted(os.listdir(基)):
        p = os.path.join(基, d, "SKILL.md")
        if os.path.exists(p):
            出[d] = io.open(p, encoding="utf-8").read()
    return 出


def 抽判据(txt: str) -> set:
    """★ 把卡里所有「会改变选股/买卖/通过与否」的数字抽出来当指纹。"""
    s = set()
    for 正则, 名 in 判据模式:
        for m in 正则.finditer(txt):
            s.add(f"{名}::{m.group(0).strip()}")
    return s


