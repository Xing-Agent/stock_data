def 分档(版本名: str) -> str:
    """★★★ 把版本名归到三档 —— ★ Lin 要的「原著 / 行业最好 / 我们调的」"""
    s = 版本名
    if "原著" in s:
        return "原著版"
    if "行业" in s:
        return "行业版"
    if "XING" in s or "xing" in s:
        return "XING 版"
    return "其它版本"


def 判定大白话(j: str) -> str:
    """★★★★★ 把台账的判定原话翻成一句人话 —— 🔴 **原话照抄在后面，不许丢**"""
    if "负且过" in j or "测出来了·负" in j:
        return "**测出来了，而且是输的** —— 这十一年里它不如同期直接买大盘"
    if "测不出" in j:
        return "**测不出** —— 结果在噪声里，我们没法说它行还是不行"
    if "只是方向" in j:
        return "**只看出一个方向，不算测出来** —— 三次结果同向，但都不够强"
    if "还不算数" in j and "笔数" in j:
        return "**还不算数** —— 信号太少（不到 100 笔），没法判"
    if "台账无此条目" in j or "台账里没有" in j:
        return "**台账里没有这一条**"
    if "研究框架" in j:
        return "**这是研究方法，不产生买卖信号** —— 所以没有可回测的东西"
    if "测出来了" in j and "负" not in j:
        return "**测出来了，是赢的**"
    if "两把尺子打架" in j:
        return "**两把尺子打架，不算数** —— 逐笔和组合层给了相反的符号"
    if "数不可用" in j:
        return "**这一轮的数不能用** —— 测试本身出了问题，要重跑"
    return j


def 读块():
    t = io.open(SRC, encoding="utf-8").read()
    out = []
    for b in re.split(r"\n### (?=[一-鿿]-\d+)", t)[1:]:
        行 = b.split("\n")
        头 = 行[0].strip()
        m = re.match(r"([一-鿿])-(\d+)\s*·\s*(.*)", 头)
        if not m:
            continue
        d = {"派": 派名.get(m.group(1), m.group(1)), "id": f"{m.group(1)}-{m.group(2)}",
             "名": m.group(3).strip(), "原文块": b}
        for f in ["一句话", "怎么买", "怎么退出", "什么时候用", "谁不该用", "最难受的时候"]:
            mm = re.search(rf"\*\*{f}\*\*[：:]\s*([^\n]*)", b)
            d[f] = mm.group(1).strip() if mm else None
        mm = re.search(r"\*\*判定\*\*[：:]\s*([^|\n]*)", b)
        d["判定"] = mm.group(1).strip() if mm else "—"
        mm = re.search(r"\*\*相邻三点\*\*[：:]\s*([^|\n]*)", b)
        d["相邻三点"] = mm.group(1).strip() if mm else "—"
        mm = re.search(r"\*\*第 10 格（什么情况下别用）\*\*[：:]\s*([^\n]*)", b)
        d["第10格"] = mm.group(1).strip() if mm else None
        # ★ 版本表
        版 = []
        for l in b.split("\n"):
            if not l.startswith("|") or l.count("|") < 10:
                continue
            c = [x.strip() for x in l.strip("|").split("|")]
            if c[0] in ("版本", "策略") or set(c[0]) <= set("-: "):
                continue
            版.append(c)
        d["版本"] = 版
        out.append(d)
    return out


