ORDER = ['能源', '原材料', '工业', '可选消费', '日常消费', '医疗保健', '金融', '信息技术', '通信服务', '公用事业', '房地产']


def sector(sic):
    s = int(sic)
    for a, b, g in RULES:
        if a <= s <= b: return g
    return None


def main(step1, siccsv, out_csv, out_map):
    title = {r['sic']: r['title'] for r in csv.DictReader(open(siccsv))}
    rows = json.load(open(step1)); today = date.today().isoformat()
    out = []
    for s, name, cik, sic, src in rows:
        if sic:
            g = sector(sic)
            out.append(dict(代码=s, 公司名=name, 一级行业=g or '取不到(SIC 不在对照表里)', 二级行业=title.get(str(int(sic)), ''), SIC=str(int(sic)),
                            来源=f'{src};一级按 SIC 区间对照表折到 GICS 11 板块', cik=cik or '', 取数日期=today, 备注='只有最新分类'))
        else:
            out.append(dict(代码=s, 公司名=name, 一级行业='金融', 二级行业='业务发展公司(BDC)', SIC='', 来源='SEC 没给 SIC;按公司类型判定(BDC 是投资公司)',
                            cik=cik or '', 取数日期=today, 备注='只有最新分类;不是 SIC 推出来的'))
    with open(out_csv, 'w', newline='', encoding='utf-8-sig') as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0])); w.writeheader(); w.writerows(out)
    with open(out_map, 'w', newline='', encoding='utf-8-sig') as fh:
        w = csv.writer(fh); w.writerow(['SIC 起', 'SIC 止', 'GICS 一级(中文)', '说明'])
        for a, b, g in RULES: w.writerow([a, b, g, ''])
    from collections import Counter
    c = Counter(o['一级行业'] for o in out)
    print(len(out), [(k, c[k]) for k in ORDER], {k: v for k, v in c.items() if k not in ORDER})


if __name__ == '__main__':
    main(*sys.argv[1:])
