#!/usr/bin/env bash
# ★★★ 重测串跑链 —— ★ 一族一个进程，跑完就退出把内存还给系统。
#
# ★★ 为什么要这样：22 年 × 3,858 只整批跑会 OOM（机器 7 GB，1107 栽了三次，exit 137）。
# ★★★ 可续跑：每条臂的结果按 label 的 sha256 存成单独文件，
#   已经有结果的臂会被直接跳过 —— 所以这个脚本**可以反复重跑，不会重复算**（规矩⑩）。
#
# ★ 顺序（《102》第七节）：
#   1. B 段 2015~2025 四族
#   2. A 段 2004~2014 四族   ← ★★ 两段齐了才能做滚动前推（A 段挑 / B 段验）
#
# ════════════════════════════════════════════════════════════════════════
# ★★★★★ 1109 主路（第 2 次唤醒）改了三件 —— ★ 台账《92》「下一轮先做③」
#
# ★★★ ① **取消默认臂目录**（原来默认写 `arms_1107`）。
#   ★ 为什么：Lin 1109 拍板第 3 条把 `arms_1107/` 挪进 `作废_假接缝面板_1109/` 之后，
#     ★★ 那 84 个文件原来**顺带起着「拦住串跑」的作用**（续跑按 sha256 全跳过，
#       1108 第 5~7 次 + 1109 第 1 次唤醒**四次**都是靠「跑了也白跑」躲过去的）——
#     ★★★ 挪走之后默认目录空了，★★★★★ 照默认跑会**真的开跑整批（几小时）**，
#       而且跑完落在一个**出数侧明令拒读**的名字里。
# ★★★ ② 跑前两道硬闸（都是现算，加起来十几秒，★ 不是「我记得面板是对的」）：
#   · `跑前查派生物_1107.py` —— 缺面板/缺包就停（规矩 60，★ 省掉跑到装池才报错的 560 秒）
#   · `面板指纹_1108.py`     —— ★★★ 回答「我手上这张面板是哪一张」（规矩 70）。
#     ★★★★★ 这一道就是 1108 两路撞车那件的根（《131》）：代码一样、自证全过、数对不上。
# ★★ ③ 已完成臂数那两行原来写死 `arms_1107/` → 改成跟着 $XING_ARMS_DIR。
# ════════════════════════════════════════════════════════════════════════
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT" || exit 1
LOG="${XING_LOG:-${TMPDIR:-/tmp}/串跑_1107.log}"
mkdir -p "$(dirname "$LOG")"

say() { echo "[$(date '+%m-%d %H:%M:%S')] $*" | tee -a "$LOG"; }

# ───────────────────────────────────────── 闸一：臂目录和曲线目录必须显式写
if [ -z "${XING_ARMS_DIR:-}" ] || [ -z "${XING_NAV_DIR:-}" ]; then
  cat <<'EOT'
★★★★★ 停跑 —— 串跑从 1109 起**没有默认臂目录了**（规矩⑯ 响亮失败 + 规矩㊻ 改结构）。

★ 为什么：原来的默认值 `arms_1107/` 装的是**假接缝那一批**（《131》《135》），
  ★★ Lin 1109 拍板第 3 条已经把它挪进 `作废_假接缝面板_1109/` →
  ★★★ 默认目录空了，照默认跑**不再是「跑了也白跑」，而是真的开跑几小时**。

★★★ 要起一批新的，两件都显式写（★ 后缀必须一样，别让臂和曲线配错对）：
  XING_ARMS_DIR=arms_<这批叫什么>_<日期> \
  XING_NAV_DIR=日净值_<同一个后缀> \
    bash probe/重测_1107/串跑_1107.sh

★ 目前「口径 + 面板」两处都对的那一批是： arms_修分红_1108/ + 日净值_修分红_1108/
  ★★ 想续跑/补算那一批 → 把这两个名字原样填进去（已有的臂会按 sha256 跳过）。
★★★ 想读那批作废的（就是要复现那个错）→ 不走本脚本，见
  `probe/重测_1107/作废_假接缝面板_1109/为什么作废.md` 第五节。
EOT
  exit 1
fi

say "★★★ 串跑跑前自检 —— 臂目录 $XING_ARMS_DIR · 曲线目录 $XING_NAV_DIR"

# ───────────────────────────────────────── 闸二：派生物齐不齐（规矩 60）
python3 probe/重测_1107/跑前查派生物_1107.py 2>&1 | tee -a "$LOG"
RC=${PIPESTATUS[0]}
if [ "$RC" -ne 0 ]; then
  say "★★★★★ 停跑 —— 跑前查派生物 RC=$RC（缺面板或缺包）。★ 按上面给的命令补齐再起。"
  exit 1
fi

# ───────────────────────────────────────── 闸三：★★★ 面板是哪一张（规矩 70）
# ★★★★★ 1108 两路撞车那件的根就在这里：代码一样、自证全过、数对不上 ——
#   ★ 因为一边是修接缝那张、一边是假接缝那张。★★ 这一道约 2~4 秒，不许跳。
python3 probe/审计复核_1108/面板指纹_1108.py 2>&1 | tee -a "$LOG"
RC=${PIPESTATUS[0]}
if [ "$RC" -ne 0 ]; then
  say "★★★★★ 停跑 —— **面板指纹不是修接缝版**（规矩 70）。"
  say "★ 跑错面板不如不跑：这一批跑完也**不许进任何一句结论**（同《131》那 84 条的下场）。"
  say "★★ 重烤： python3 probe/并池_1107/烤并池_1107.py （约 132 秒），然后再起串跑。"
  exit 1
fi
say "✓✓ 三道闸全过 —— ★ 面板是修接缝版，派生物齐，臂/曲线目录已显式指定。"

say "★★★ 串跑开始 —— 口径：全收益（分红再投，两侧同口径，《104》拍板）"

数臂() { ls "probe/重测_1107/$XING_ARMS_DIR/" 2>/dev/null | wc -l; }

for WIN in "B_2015到2025|2015-01-01|2025-12-31" "A_2004到2014|2004-01-02|2014-12-31"; do
  IFS='|' read -r NAME START END <<< "$WIN"
  for FAM in 大波段 突破 震荡; do
    say "▶▶ $NAME · $FAM 开跑"
    XING_WIN_NAME="$NAME" XING_WIN_START="$START" XING_WIN_END="$END" XING_FAM="$FAM" \
      python3 probe/重测_1107/跑重测_1107.py >> "$LOG" 2>&1
    RC=$?
    if [ $RC -eq 0 ]; then
      say "✓✓ $NAME · $FAM 跑完"
    elif [ $RC -eq 137 ]; then
      # ★★★ 不要静默跳过 —— OOM 必须大声说出来（规矩⑯ 响亮失败）
      say "⚠⚠ $NAME · $FAM **被 OOM 杀了（137）** —— 这一族没跑完，不许进结论"
    else
      say "⚠⚠ $NAME · $FAM 退出码 $RC —— 不许进结论"
    fi
    say "   ★ 当前已完成臂数：$(数臂)"
  done
done

say "★★★ 串跑结束 —— 已完成臂数：$(数臂)"
say "★ 下一步（要人来做判断的）：配对检验（规矩㊸v2）+ 条件 alpha 交互项 + 持仓画像"
