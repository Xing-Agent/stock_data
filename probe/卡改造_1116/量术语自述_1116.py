def 卡列表():
    return [d for d in sorted(os.listdir(包)) if os.path.isfile(os.path.join(包, d, "SKILL.md"))]


def 卡文件(d):
    出 = []
    for dp, _dirs, fns in os.walk(os.path.join(包, d)):
        for fn in sorted(fns):
            if fn.endswith(".md"):
                出.append(os.path.join(dp, fn))
    return 出


def 正文(p):
    t = io.open(p, encoding="utf-8", errors="replace").read()
    切 = t.find(成绩标记)
    return t[:切] if 切 >= 0 else t          # ★★ 成绩节以后是生成器写的，不算自述


def 量术语(卡):
    """★ 返回（全仓条数, 窄口径条数, 明细）—— ★★★ 两个口径一起报，才看得出「扩了买到什么」"""
    宽, 窄, 明细 = [], [], []
    for d in 卡:
        fs = 卡文件(d)
        文本 = {f: 正文(f) for f in fs}
        skill = os.path.join(包, d, "SKILL.md")
        for 概念, 叫法 in 术语组:
            def 找(范围):
                用到 = {}
                for f in 范围:
                    for ln, 行 in enumerate(文本[f].splitlines(), 1):
                        for x in 叫法:
                            if x in 行 and x not in 用到:
                                用到[x] = {"文件": os.path.relpath(f, 包), "行": ln, "原句": 行.strip()[:120]}
                return 用到
            宽用 = 找(fs)
            窄用 = 找([skill]) if skill in 文本 else {}
            if len(窄用) >= 2:
                窄.append({"卡": d, "概念": 概念, "叫法": sorted(窄用)})
            if len(宽用) >= 2:
                h = {"卡": d, "概念": 概念, "叫法": sorted(宽用), "证据": 宽用,
                     "只在宽口径才看得见": len(窄用) < 2}
                宽.append(h)
                明细.append(h)
    return 宽, 窄, 明细


def 量数量自述(卡):
    """★★★ 新判据：「以下 N 种/类…」+ 紧跟（1~2 行内）一张能数的清单 → 数对不对。"""
    红, 对, 分母文件 = [], 0, 0
    for d in 卡:
        for p in 卡文件(d):
            分母文件 += 1
            行s = 正文(p).splitlines()
            for i, 行 in enumerate(行s):
                for m in 宣告.finditer(行):
                    s = m.group(1).strip("*")
                    n = int(s) if s.isdigit() else 汉数.get(s)
                    if not n:
                        continue
                    j = None
                    for k in (i + 1, i + 2):
                        if k < len(行s) and (列项.match(行s[k]) or 表行.match(行s[k])):
                            j = k
                            break
                    if j is None:
                        continue                      # ★★ 清单跟不上 → 看不见的一类②
                    是表 = bool(表行.match(行s[j]))
                    cnt, k = 0, j
                    while k < len(行s):
                        L = 行s[k]
                        if 是表:
                            if not 表行.match(L):
                                break
                            if 表分隔.match(L):
                                k += 1
                                continue
                            cnt += 1
                        else:
                            if 列项.match(L):
                                cnt += 1
                            elif L.strip() and L.startswith(("  ", "\t")):
                                pass                   # ★ 续行
                            else:
                                break
                        k += 1
                    if 是表:
                        cnt -= 1                       # ★ 去表头
                    if cnt <= 0:
                        continue
                    h = {"卡": d, "文件": os.path.relpath(p, 包), "行": i + 1,
                         "它说": m.group(0).strip(), "N": n, "数到": cnt, "原句": 行.strip()[:120]}
                    if n == cnt:
                        对 += 1
                    else:
                        h["★"] = (f"★★★★★ 自述说 {n}，紧跟的清单只数到 {cnt} —— "
                                  f"★★ AI 照自述去找第 {n} 项会找不到（同 #99 根因：旧句没删）")
                        红.append(h)
    return 红, 对, 分母文件


def 钉死表自查(术语明细):
    失 = []
    for f, frag, why in 人核放过:
        命 = False
        for h in 术语明细:
            for x, e in h["证据"].items():
                if e["文件"].endswith(f.split("/")[-1]) and frag in e["原句"]:
                    命 = True
        if not 命:
            # ★ 再去文件里直接找一遍（★★ 证据只留每个叫法第一处，可能错过）
            for d in 卡缓存:
                for p in 卡文件(d):
                    if p.endswith(f) and frag in 正文(p):
                        命 = True
                        break
        if not 命:
            失.append({"条": f, "片段": frag, "理由": why,
                       "★": "★★★ 配不上了 —— ★ 要么那行改过了，要么口径变了，**当没核过**"})
    return 失


