def md5(p: str) -> str:
    return hashlib.md5(io.open(p, "rb").read()).hexdigest()


def main() -> int:
    # ---- ① 先验原包是不是我记下指纹的那一份（★★★ 防 #95:改之前先确认改的是哪一版）
    对不上 = []
    for 卡, h in 原指纹.items():
        p = os.path.join(包, 卡, "SKILL.md")
        if not os.path.exists(p):
            对不上.append(f"{卡}: 文件不存在")
        elif md5(p) != h:
            对不上.append(f"{卡}: 指纹 {md5(p)[:8]} ≠ 记录的 {h[:8]}")
    if 对不上:
        print("★★★★★ 原包和我记录的指纹对不上，**什么都没改**：")
        for x in 对不上:
            print("   ", x)
        print("★★ 可能原因：包被改过，或者我指纹记错了。★★★ 先查清再跑。")
        return 1

    # ---- ② 只做加法，改之前把原文留在内存里做对比
    原文 = {}
    for 卡 in 原指纹:
        原文[卡] = io.open(os.path.join(包, 卡, "SKILL.md"), encoding="utf-8").read()

    改动 = {
        "xing-skill-builder": 四样节,
        "xing-agent-builder": 交叉引用,
    }
    for 卡, 追加 in 改动.items():
        p = os.path.join(包, 卡, "SKILL.md")
        新 = 原文[卡].rstrip("\n") + "\n" + 追加
        io.open(p, "w", encoding="utf-8").write(新)

    # ---- ③ 自证（★★★★★ 规矩㊿：自证要证到**效果**，不是证到「我跑过了」）
    print("★★★ 自证")
    失败 = []

    # 自证 a：没动的 4 张，指纹必须一字不变
    for 卡, h in 原指纹.items():
        if 卡 in 该动的:
            continue
        now = md5(os.path.join(包, 卡, "SKILL.md"))
        ok = now == h
        print(f"   {'✓' if ok else '✗'} {卡} 未被改动（指纹 {now[:8]}）")
        if not ok:
            失败.append(f"{卡} 被改了，指纹变成 {now[:8]}")

    # 自证 b：改过的 2 张，原文必须**整段原样保留**（只许加，不许删改）
    for 卡 in sorted(该动的):
        新 = io.open(os.path.join(包, 卡, "SKILL.md"), encoding="utf-8").read()
        保留 = 新.startswith(原文[卡].rstrip("\n"))
        print(f"   {'✓' if 保留 else '✗'} {卡} 原文 {len(原文[卡])} 字全部原样保留在开头"
              f"（新文件 {len(新)} 字，★ 净增 {len(新) - len(原文[卡])}）")
        if not 保留:
            失败.append(f"{卡} 的原文被动过，不是纯追加")

    # 自证 c：★★★★★ 证到**效果** —— 四样关键词补进去之前是 0 次，现在必须都 > 0
    关键词 = ["样本外", "随机", "脆弱", "起点", "已调", "不可关"]
    新全文 = "".join(
        io.open(os.path.join(包, 卡, "SKILL.md"), encoding="utf-8").read() for 卡 in 原指纹)
    旧全文 = "".join(原文[卡] for 卡 in 原指纹)
    for k in 关键词:
        旧, 新 = 旧全文.count(k), 新全文.count(k)
        ok = 新 > 旧
        print(f"   {'✓' if ok else '✗'} 「{k}」 补之前 {旧} 次 → 现在 {新} 次")
        if not ok:
            失败.append(f"关键词「{k}」没补进去（{旧} → {新}）")

    # 自证 d：★★ 没有把「建议/倾向」这类该由 Lin 定的话写进卡
