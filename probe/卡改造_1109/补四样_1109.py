四样节 = """
## 验证的四样底线（不可由用户关闭）

用户可以定「什么算好」：门槛多高、看哪个指标、要多少笔、能接受多大回撤、看多长的历史。
这些是他的偏好，由他定。

下面四样是「怎么验」，不是偏好。**任何档位都不得关闭、不得由用户指定、不得跳过。**
理由只有一句：这四样一旦可关，他拿到的数字就不再有意义，而他不会知道。

### ① 样本外区间：只有一次机会

历史数据切两段。前段供反复试，后段在确认之前不得参与任何计算、不得用于挑选参数。
用户说「调好了」，后段才跑，**且只跑一次**。跑完即失效；要再验，只能换一段他未见过的区间。

- 后段结果不得反向用于改参数。若改了参数，必须重新取一段未使用过的区间，并说明原区间已失效。
- 没有可用的未见区间时，状态为「无法做样本外检验」，不得以样本内结果代替。

### ② 对照组：由系统随机抽取，用户不得指定

同一套规则，除目标标的外，另在系统随机抽取的同类标的上运行一遍，用于区分
「规则有效」与「只在这一只上有效」。

- 抽取由系统完成。**不接受用户输入、指定、替换或重抽对照标的。**
- 对照组结果与目标结果必须同屏并列，不得只显示其中一个。
- 对照组上不成立时，结论写「样本外未被证伪」，不得写「已验证」「具备泛化能力」。

### ③ 参数脆弱度与起点敏感度

- **参数脆弱度**：用户给的每个数值门槛，同时跑它上下各一档（相邻两点），
  报三点是否同向。只有中间那点成立 = 该门槛对上了这段历史，不是规律。
  相邻两点的间距由用户给的门槛本身决定，不由我们预设。
- **起点敏感度**：同一规则换若干个起始日各跑一遍，报结果离散程度。
  换起点就变样 = 结果取决于起跑日的选择。
- 两项都必须出数。算不出来时写「算不出来」，**不得与「分数差」混成一个数**。

### ④ 调参次数计数器

同一条规则从建立到当前的修改次数，**在结果页面明文显示**，例：已调 N 次。

- 计数不得清零、不得隐藏、不得折叠。
- 调参次数本身不构成拦截，但必须与结论同屏：调了很多次才通过与第一次就通过，不是一回事。

### 三档：谁定标准（Lin 2026-11-09 拍板）

| 档 | 门槛由谁定 | 用在哪 | 上面四样 |
|---|---|---|---|
| 自定 | 用户自己的规矩 | 自己看、自己用 | 照常全跑、全显示 |
| 默认 | 我们这一套 | 用户没有自己的规矩时 | 照常全跑、全显示 |
| 过审 | **只能是我们这一套** | 要分享给他人、要上架 | **全跑、全显示，且不可关** |

三档的差别只在「门槛谁定」，不在「要不要验」。四样在三档里都不可关闭。
"""

