def validate() -> list[dict]:
    """★★★ 强制登记:每一条都必须写满;写不满就 `raise`。"""
    cards = {m["method_id"]: m for m in json.load(
        open(INDEX_JSON, encoding="utf-8"))["method_cards"]}
    ji = [k for k in cards if k.startswith("基")]
    missing = sorted(set(ji) - set(PLAN), key=lambda x: int(x.split("-")[1]))
    if missing:
        raise ValueError(f"★★★ 这 {len(missing)} 条基本面方法没盘点:{missing} —— "
                         f"★ 不许漏。")
    extra = sorted(set(PLAN) - set(ji))
    if extra:
        raise ValueError(f"★ 盘点里有不存在的方法号:{extra}")

    rows = []
    for mid in sorted(PLAN, key=lambda x: int(x.split("-")[1])):
        d = PLAN[mid]
        _req(d, mid, ("名", "等级", "卡在什么上", "次要卡点",
                      "要买什么/要问什么", "本地已核实", "本地无法核实",
                      "无自由参数子集"))
        if d["等级"] not in LEVELS:
            raise ValueError(f"★ {mid} 的等级 {d['等级']!r} 不在四态里")
        if d["等级"] == "乙" and not d.get("用什么补 / 覆盖率"):
            raise ValueError(
                f"★★★ {mid} 判成乙类,★ 但没写「用什么补 / 覆盖率」—— "
                f"乙类必须写明替代字段和覆盖率,否则它和丙类分不开。")
        card = cards[mid]
        rows.append({
            "方法号": mid,
            "名": d["名"],
            "等级": d["等级"],
            "原著声明的使用条件": card.get("time_horizon_or_application"),
            "方法卡 data_requirement": card.get("data_requirement"),
            "出处完整性(原文)": (card.get("evidence_four_columns") or {}).get(
                "source_rule_completeness"),
            "卡在什么上": d["卡在什么上"],
            "次要卡点": d["次要卡点"],
            "用什么补 / 覆盖率": d.get("用什么补 / 覆盖率", ""),
            "要买什么/要问什么": d["要买什么/要问什么"],
            "本地已核实": d["本地已核实"],
            "本地无法核实": d["本地无法核实"],
            "无自由参数子集": d["无自由参数子集"],
            "★本轮跑": bool(d.get("★本轮跑")),
            "★本轮跑子集": bool(d.get("★本轮跑子集")),
        })
    return rows


