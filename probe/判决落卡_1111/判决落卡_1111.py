    #     ★★★★★ 而卡上那一句写着「答成绩题就按这一句」→ **它就成了对外依据**。
    #   ★ 修法：**对外那句只留判定本体**，括号里的内部口径整段搬进「⛔ 不给用户看」。
    #     ★★★ 一个字都不删（6.10：精简永远不许减掉代价/坏消息/归属），只是换了位置。
    内部词 = ["t≥", "t ≥", "多重检验", "显著", "运气约给", "Newey", "个检验"]
    判, 判内部 = 判全, ""
    import re as _re
    for _m in _re.finditer(r"（[^（）]*）", 判全):
        if any(w in _m.group(0) for w in 内部词):
            判内部 = _m.group(0)
