def _读按年():
    # ★★★★★ 这里一律用 `_i()` 而不是 `int()` —— ★ csv 里的数是 `10.0` 这种，
    #   ★★ 因为技-8 那一行没有数据，整列被当成浮点写出来了。★★★ 直接 int('10.0') 会炸。
    import csv, collections, os
    def _i(x):
        return int(float(x))
    f = os.path.join(ROOT, "probe/笔数不足_按年一致性_1112/按年一致性_1112.csv")
    if not os.path.exists(f):
        return {}
    by = collections.defaultdict(list)
    with io.open(f, encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            if row.get("条目"):
                by[row["条目"]].append(row)
    out = {}
    for cid, rows in by.items():
        好 = [r for r in rows if (r.get("有交易年份") or "").strip()]
        if not 好:
            out[cid] = {"★": "做不了", "说": "这一条**一个流水文件都没有** —— ★★ 补不了证据，照实说"}
            continue
        # ★ 同一条臂在两个跑批里各有一份 → 按臂名去重，取笔数最大的那份
        seen = {}
        for r in 好:
            k = r["臂"]
            if k not in seen or _i(r["笔数"]) > _i(seen[k]["笔数"]):
                seen[k] = r
        rows2 = list(seen.values())
        # ★★★★★ **不再给「丙成立 / 不成立」这个判语**（2026-11-12 改）：
        #   🔴 ★★ 第一版给了，★★★ 结果把两件很不一样的事混成一个词 ——
        #      基-1 = 18 正 / 1 负 · 基-3 = 11 正 / 16 负，**同一个标签**。
        #   ★★★★★ 再分一档（比如「负年 ≤ 1 也算同向」）就等于**我们自己发明一个阈值** → 红线①。
        #   ✅ 所以只给**正年 / 负年的原始数**，★ 结论由 Lin 定（★★ 共用边界⑨：只给数字）。
        年年同向 = all(r["★按年"].startswith("✅") or r["★按年"].startswith("❌") for r in rows2)
        正 = sum(_i(r["正年"]) for r in rows2)
        负 = sum(_i(r["负年"]) for r in rows2)
        out[cid] = {
            "★": "年年同向" if 年年同向 else "有正有负",
            "臂数": len(rows2),
            "笔数区间": f'{min(_i(r["笔数"]) for r in rows2)} ~ {max(_i(r["笔数"]) for r in rows2)}',
            "年份区间": f'{min(_i(r["有交易年份"]) for r in rows2)} ~ {max(_i(r["有交易年份"]) for r in rows2)}',
            "正年合计": 正, "负年合计": 负,
            "逐臂": [f'{r["臂"]}：{_i(r["有交易年份"])} 年里 正 {_i(r["正年"])} / 负 {_i(r["负年"])}  {r["★按年"]}'
                   for r in rows2],
        }
    return out


