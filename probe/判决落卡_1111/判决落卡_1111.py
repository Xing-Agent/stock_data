    头 = [c.strip() for c in lines[hi].strip("|").split("|")]
    assert len(头) == 19, f"🔴 主表列数 {len(头)}，预期 19"

    def 列(关键词, 必含=None):
        """按表头文字找列号，★ 找不到就报错，不猜位置"""
