def main():
    src = io.open(P, encoding="utf-8").read()
    if "①归因基准" in src:
        print("【跳过】已经改过了")
        return
    new = src
    for 旧, 新, 说 in 改:
        n = new.count(旧)
        assert n == 1, f"🔴 「{说}」锚点命中 {n} 次，应为 1"
        new = new.replace(旧, 新, 1)
        print(f"  ✅ {说}")

    # ★ 表头前加一段说明（★★ 插在主表那一行之前）
    表头 = "| 策略 | 派 | 版本 | 笔数 | ★★★ ①归因基准⚠内部·对自己赛道alpha年% |"
    assert new.count(表头) == 1
    new = new.replace(表头, 表头说明 + "\n" + 表头, 1)
    print("  ✅ 主表表头前加了「归因基准不是对外主基准」那一段")

    # ── 自证：抹掉所有被改的标签后，两边逐字相同（★★★ 证明没动数字）──
    def 规约(t):
        for 旧, 新, _ in 改:
            t = t.replace(新, "《TOKEN》").replace(旧, "《TOKEN》")
        t = t.replace(表头说明, "")
        return re.sub(r"\s+", "", t)
    a, b = 规约(src), 规约(new)
    print(f"\n【自证①】抹掉被改标签后逐字相同：" + ("✅" if a == b else "🔴"))
    if a != b:
        for i, (x, y) in enumerate(zip(a, b)):
            if x != y:
                print(f"   首个差异在第 {i} 字：旧…{a[i-60:i+60]}  新…{b[i-60:i+60]}")
                break
        raise SystemExit(1)

    # ── 自证②：所有数字一个没变 ──────────────────────────
    数 = lambda t: re.findall(r"-?\d+\.?\d*", t)
    d1, d2 = 数(src), 数(new)
    # ★ 新增文字里带了 6.2 / 7 / 8 / 3.1 / 40 / 34 / 6 等数，所以比的是「旧的全在新的里且顺序不乱」
    print(f"【自证②】旧文数字 {len(d1)} 个 · 新文 {len(d2)} 个（★ 新增说明文字本身带数字）")
    # ★★★★★ 判据改过一次（★ 记在这里，免得下次再踩）：
    #   第一版用 difflib 按**顺序**比 → 报「丢了 -13 -17 -18 -22 -23」。
    #   ★★ 一查是假警报：改口一之②把那 12 条**重新分了三组**，顺序变了，数字没少。
    #   ★★★ 所以判据从「顺序相同」改成「**个数相同**」（多重集），
    #     ★ 顺序本来就不该是判据 —— 它不承载任何信息。
    from collections import Counter
    c1, c2 = Counter(d1), Counter(d2)
    丢 = {k: c1[k] - c2[k] for k in c1 if c2[k] < c1[k]}
    print(f"【自证②】**个数变少的数字** = {len(丢)} 种 " + ("✅ 一个都没丢" if not 丢 else f"🔴 {丢}"))
    assert not 丢
    多 = {k: c2[k] - c1[k] for k in c2 if c2[k] > c1.get(k, 0)}
    print(f"【自证②】新增的数字（★ 应全部来自新写的说明文字）：{多}")

    if DRY:
        print("\n【DRYRUN】未写盘")
        return
    io.open(P, "w", encoding="utf-8").write(new)
    print(f"\n【写盘】{P}  {len(src)} → {len(new)} 字")


if __name__ == "__main__":
    main()
