os.makedirs(OUT, exist_ok=True)
rep = {}
for key, arr, pre, fn in [('CPI', CPI, 'cpi', 'CPI_发布日期_2015到2021.csv'), ('EMP', EMP, 'empsit', '非农_发布日期_2015到2021.csv')]:
    rows, odd, diff = [], [], []
    for i, s in enumerate(arr):
        d = date(int(s[4:]), int(s[:2]), int(s[2:4]))
        y, m = divmod(2014 * 12 + 11 + i, 12); ref = f'{y}-{m + 1:02d}'
        sch = SCHED[key][i]
        if sch != d.isoformat(): diff.append((ref, d.isoformat(), sch))
        note = []
        if key == 'EMP':
            if d.weekday() != 4: note.append(f'不是周五(周{WD[d.weekday()]})')
            if d.day > 7: note.append('不是当月第一个周五')
        else:
            if not 10 <= d.day <= 20: note.append(f'不在月中(当月 {d.day} 号)')
        if note: odd.append((ref, d.isoformat(), ';'.join(note)))
        rows.append(dict(release_date=d.isoformat(), release_time_et='08:30', ref_month=ref, source_url=f'{ARCH}{pre}_{s}.htm',
                         备注=';'.join(note), 日程页核对=f'一致(bls.gov/schedule/{d.year}/home.htm)' if sch == d.isoformat() else f'不一致:日程页 {sch}',
                         正文核对='一致(新闻稿抬头 8:30 a.m. 同一天)' if f'{pre}_{s}' in TEXT else ''))
    assert len({r['release_date'] for r in rows}) == len(rows)
    with open(f'{OUT}/{fn}', 'w', newline='', encoding='utf-8-sig') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    random.seed(515 + len(key))
    samp = [r for y in range(2015, 2022) for r in random.sample([r for r in rows if r['release_date'].startswith(str(y))], 2)]
    rep[key] = dict(n=len(rows), years={y: sum(r['release_date'].startswith(str(y)) for r in rows) for y in range(2015, 2022)}, diff=diff, odd=odd,
                    samp=[(r['ref_month'], r['release_date'], r['source_url']) for r in samp])
for k, v in rep.items():
    print(k, v['n'], v['years'], '日程页不一致', v['diff']); print(' 不合规律', v['odd'])
    for s in v['samp']: print(' 抽查', *s)
