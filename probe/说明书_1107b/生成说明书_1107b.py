def 同向(ar: list) -> str:
    xs = [a["差pct"] for a in ar if isinstance(a.get("差pct"), (int, float))]
    hs = {a.get("★流水哈希") for a in ar if a.get("★流水哈希")}
    if len(ar) >= 2 and len(hs) == 1 and len(ar) == len([a for a in ar if a.get("★流水哈希")]):
        return "★★★ **相邻三点没测到** —— 三个点的流水哈希一模一样（参数没生效，规矩⑪）"
    if len(xs) < 3:
        return f"不足三点（{len(xs)}）"
    if all(x > 0 for x in xs):
        return "三点同向·正"
    if all(x < 0 for x in xs):
        return "三点同向·负"
    return "不同向"


