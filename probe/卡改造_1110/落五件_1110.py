# ========== 2A：正面模板（★ 不是禁令，是模板） ==========
模板节 = """
## 用户没给数字时：只给口径，不给数（2026-11-10 · Lin 拍板「不许带数」）

用户说「量跟上来的突破票」「跌破哪里算走坏」这类话、**没有给出任何数字**时：

**不许**自己挑一个数填进去，**也不许**给「宽松 1.2 倍 / 中等 1.5 倍 / 严格 2 倍」
这种带数的三档预设。加一句「这不是历史验证后的最优值」**不足以**解除它 ——
写出来的那个数会成为事实上的默认值。

**照这个形状给**（正例，来自实测表现最好的那一次回答）：

> 「量跟上来」可以按这几种口径之一来判，**门槛和窗口由你定**：
> · 相对**近 N 日均量**的倍数
> · 相对**近 N 日中位量**的倍数
> · 近 N 日成交量的**分位数**
> 你给 N 和门槛，我就按它筛。

同样的形状适用于：「跌破哪里算走坏」→ 给「近 N 日最低点 / N 日均线 / 入场价下方 X%」
这几种**口径**，N 和 X 由用户定，不要替他选 20 日或 50 日。

用户自己给了数字、窗口或口径的，**直接沿用，不要再问一遍**。

本条的理由只有一句：**我们没有测过那个数。** 一个没测过的数一旦显示出来，
用户多半就用它了 —— 那等于我们发明了一个门槛，再把它当成行业标准交给他。
"""

# ========== C 组四件：跨卡标准 ==========
大师标准 = """
## 大师卡的两条标准（2026-11-10 · Lin 拍板，C 组第一轮提出）

★★ 另有「风险怎么说」「成绩怎么说」两条 —— **本次不写**：
原稿用一句话把所有大师卡都归成「未验证」，Lin 指出这与我们实际做过的回测不符。
一查确实太宽：22 张大师卡里 6 张在策略台账里能对上链，16 张对不上，而对得上的那几张
各是不同的结论（测出来了·负 / 测不出 / 笔数太少算不出 / 引擎做不到 / 数据不够）。
按「『算不出来』和『分数差』分开记，不许混成一个数」，这两条要分四类写，待拍板。

### 一、首轮：直接答，不要先问一轮

用户第一句话问到某位大师的方法时，**按默认口径直接作答**，同时：
- **写明用的是什么默认口径**（例如「加权 QQQ，不是等权 QQQE」）
- **发现用户的前提有误就当场纠正**（例如用户说「这轮上涨」，而近月指数实际在跌）
- 影响结论的关键口径缺失时，**答完之后**再问最少的问题，不要答之前先问一轮

理由：让用户干等一轮才拿到第一句有用的话，是我们自己造的摩擦。

### 二、禁句清单：这四类话一句都不许说

1. 「能跑赢大盘」及任何同义表述
2. 「这方法准 / 很有效」
3. 「**照这个做就行**」
4. 「**我帮你决定**」

后两条比「预测」更该禁：预测只是说错一个数，这两句是**让用户依赖我们**。
被逼问时的挡法以这四条为边界，具体句式各卡可以不同。
"""


def md5(p):
    return hashlib.md5(io.open(p, "rb").read()).hexdigest()


def main() -> int:
    读 = lambda p: io.open(p, encoding="utf-8").read()
    共用们 = sorted(glob.glob(os.path.join(包, "*", "references", "shared", "common_boundaries.md")))
    if len({md5(p) for p in 共用们}) != 1:
        print("★★★★★ 共用文件本来就不一致 —— 先查清，本次什么都不改。")
        return 1
    原共用 = 读(共用们[0])
    新共用 = 原共用.rstrip("\n") + "\n" + 大师标准

    # ★★ 2A 的模板落到两张会碰到这件事的卡
    两张 = ["xing-screener", "xing-technical-analyst"]
    计划 = {}
    原文 = {}
    for 卡 in 两张:
        p = os.path.join(包, 卡, "SKILL.md")
        原文[p] = 读(p)
        计划[p] = 原文[p].rstrip("\n") + "\n" + 模板节

    # ★★★ screener 第 106 行那处**唯一真的带数**的地方：改掉，但保留「想改一句话就能改」
    sp = os.path.join(包, "xing-screener", "SKILL.md")
    旧句 = "│ ★★ 一条要说的:你说的「量跟上来」我按**放量 1.5 倍**     │"
    新句 = "│ ★★ 一条要说的:「量跟上来」的**口径和门槛由你定** ——     │"
    带数处 = 原文[sp].count(旧句)
    if 带数处:
        计划[sp] = 计划[sp].replace(旧句, 新句)

    # ---- 自证
    print("★★★ 自证（★ 写盘前）")
    失败 = []

    for p in 计划:
        卡 = os.path.basename(os.path.dirname(p))
        抹 = lambda s: s.replace(旧句, "").replace(新句, "")
        ok = 抹(计划[p]).startswith(抹(原文[p]).rstrip("\n"))
        print(f"   {'✓' if ok else '✗'} {卡} 原文原样保留（★ 净增 {len(计划[p])-len(原文[p])} 字）")
        if not ok:
            失败.append(f"{卡} 不是纯追加")

    print(f"   {'✓' if 带数处 == 1 else '✗'} screener 那处唯一带数的句子被改掉（找到 {带数处} 处）")
    if 带数处 != 1:
        失败.append(f"screener 带数句找到 {带数处} 处，预期 1 处")

    # ★★★★★ 证到效果：改完之后，卡里不许再出现那个我们没测过的数
    新screener = 计划[sp]
    for 数 in ["放量 1.5 倍", "放量1.5倍"]:
        剩 = 新screener.count(数)
        print(f"   {'✓' if 剩 == 0 else '✗'} screener 里「{数}」剩 {剩} 处")
        if 剩:
            失败.append(f"screener 里还剩「{数}」")

    # ★★ C 组四件真的进了共用边界
    for k, 名 in [("直接答", "C-4 首轮直接答"), ("我帮你决定", "C-7 禁句"),
                 ("待拍板", "★★ C-5/C-6 明确标成待拍板")]:
        旧n, 新n = 原共用.count(k), 新共用.count(k)
        ok = 新n > 旧n
        print(f"   {'✓' if ok else '✗'} {名}：「{k}」{旧n} → {新n} 次")
        if not ok:
            失败.append(f"{名} 没落进共用边界")

    # ★★★ 台账数字必须逐字对得上《93》（★ 不许我自己改写判决）
    # ★★★★★ 反向自证：C-5/C-6 的错稿**不许**出现在这一版里
    for 错 in ["一律按「未验证 / 教学用途」", "大师方法本身没有回测成绩"]:
        剩 = 大师标准.count(错)
        print(f"   {'✓' if 剩 == 0 else '✗'} 被推翻的错稿「{错[:16]}…」剩 {剩} 处")
        if 剩:
            失败.append(f"错稿还在：{错[:20]}")

    # ★ 没有把「建议」写进卡
    for k in ["建议挂", "我倾向", "我建议"]:
        if k in 大师标准 or k in 模板节:
            失败.append(f"出现禁词「{k}」")
    print(f"   {'✓' if not 失败 or all('禁词' not in x for x in 失败) else '✗'} 没把「建议/倾向」写进卡")

    if 失败:
        print("\n★★★★★ 自证不通过，**一个字节都没写**：")
        for x in 失败[:10]:
            print("   ", x)
        return 1
    if 试跑:
        print("\n★★ XING_DRYRUN=1 —— 自证通过，按要求没写盘。")
        return 0

    for p in 共用们:
        io.open(p, "w", encoding="utf-8").write(新共用)
    for p, c in 计划.items():
        io.open(p, "w", encoding="utf-8").write(c)
    print(f"\n   {'✓' if len({md5(p) for p in 共用们}) == 1 else '✗'} 写盘后 {len(共用们)} 份共用文件指纹全同")
    print(f"\n★★ 写完。★ 共用边界 {len(原共用)} → {len(新共用)} 字 · 卡 {len(计划)} 张。")
    print("★★★★★ 这一处改动能管到 **39 张卡** —— ★★ 昨天之前只有 8 张引用共用边界，"
          "★★★ 同样的改动当时只管得到五分之一。")
    print("★★★ 没查到的：**写进去不等于模型会照着做** —— C 组那四条要靠下一轮体验测。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
