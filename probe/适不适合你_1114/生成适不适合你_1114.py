def 取行名单():
    t = io.open(台账, encoding="utf-8").read()
    名单, 见过 = [], []
    for m in re.finditer(r"^\|\s*\*\*([^ |*]+)\s*·\s*([^|*]+)", t, re.M):
        k = m.group(1).strip()
        if k not in 见过:
            见过.append(k); 名单.append((k, m.group(2).strip()))
    return 名单


def 读卡(名):
    p = os.path.join(LIB, 名 + ".md")
    if not os.path.exists(p):
        return {}
    t = io.open(p, encoding="utf-8").read()
    g = {}
    for key in ("什么时候用", "谁不该用"):
        m = re.search(rf"^{key}\s+(.+)$", t, re.M)
        if m:
            g[key] = m.group(1).strip()
    return g


