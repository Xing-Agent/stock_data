def 读卡(名: str) -> dict:
    p = os.path.join(LIB, 名 + ".md")
    if not os.path.exists(p):
        return {}
    t = io.open(p, encoding="utf-8").read()
    g = {}
    for key in ("什么时候用", "谁不该用", "最难受的时候", "规则归属"):
        m = re.search(rf"^{key}\s+(.+)$", t, re.M)
        if m:
            g[key] = m.group(1).strip()
    m = re.search(r"\*\*④ 当前允许用途\*\*[：:]\s*(.+)", t)
    g["④用途"] = m.group(1).strip() if m else "?"
    m = re.search(r"\*\*③ XING 当前验证\*\*[：:]\s*(.+)", t)
    g["③验证"] = m.group(1).strip() if m else "?"
    return g


def 一条(方法: str, 链名单: list[str]) -> str:
    c = 读卡(方法)
    if not c:
        return f"## {方法}\n\n⬜ ★★★ **方法卡原文找不到** —— ★ 这一格空着,不猜。\n\n---\n\n"
    cls, 判据 = 分类.get(方法, ("?", "★★★ **我没分类** —— 要人判"))
    档, 出处 = 档位.get(方法, 默认档)
    L = [f"## {方法}", "",
         f"> ★ 对应 **{len(链名单)}** 条链：" + " · ".join(x.split("/")[-1][:30] for x in 链名单[:4])
         + (" …" if len(链名单) > 4 else ""), ""]

    L.append("### ★ 第 10 格草稿")
    L.append("")
    for 类 in ("① 市场环境", "② 人", "③ 票", "④ 钱"):
        键 = 类.split()[-1]
        L.append(f"**{类}**")
        if 键 == cls or (键 == "市场环境" and cls == "环境"):
            L.append(f"  · {c.get('谁不该用','?')}")
            L.append(f"    ★ 档位：**{档}** —— {出处}")
            if 方法 in 够具体:
                ok, why = 够具体[方法]
                L.append(f"    ★★ 能不能写成规则：{'✅ **能**' if ok else '❌ **不能**'} —— {why}")
                if not ok:
                    L.append("    ★★★ 所以这一格要写明：**怎么判没有公认标准，我们现在判不了。**")
            if 方法 in 翻方向:
                L.append(f"    {翻方向[方法]}")
        elif 键 == "市场环境" and "最难受的时候" in c:
            L.append(f"  · ★ 原著没把它写成「不该用」，但写了**最难受的时候**：{c['最难受的时候']}")
            L.append(f"    ★★ 档位：**{档}** · ★★★ 只作展示，**不装闸**")
        else:
            L.append("  · ⬜ 原文没写。")
        L.append("")

    if 方法 in 额外:
        L.append("**★★★ 另外要让用户知道的**")
        for x in 额外[方法]:
            L.append(f"  · {x}")
        L.append("")

    L.append("### ★ 核这一条时看两样")
    L.append("")
    L.append(f"| | |\n|---|---|")
    L.append(f"| ★ **我把那句话判成了「{cls}」** | {判据} |")
    L.append(f"| ★★ **原文「什么时候用」** | {c.get('什么时候用','?')}　★★★（只作展示，不装闸） |")
    L.append(f"| ★ **卡自己的用途限制** | {c.get('④用途','?')} |")
    L.append(f"| ★ **卡自己的验证栏** | {c.get('③验证','?')} |")
    L.append("")
    L.append("---")
    L.append("")
    return "\n".join(L)


