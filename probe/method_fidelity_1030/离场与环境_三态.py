def check_and_count() -> dict:
    live = set(live_configs())
    mapped = set(MASTER_EXIT) | {c for cs in METHOD_OF.values() for c in cs}
    errs = []
    missing = live - mapped
    extra = mapped - live
    if missing:
        errs.append(f"★★ 配置目录里有这张表没覆盖的策略配置:{sorted(missing)} "
                    f"—— ★ 「没查」不许和「查了一致」长得一样")
    if extra:
        errs.append(f"★ 这张表写了但配置目录里不存在:{sorted(extra)}")
    for name, tbl in (("⑤环境", REGIME), ("②离场", EXIT)):
        for k in METHOD_OF:
            if k not in tbl:
                errs.append(f"{name} 缺方法 {k}")
            else:
                r = tbl[k]
                if r["态"] == "乙" and r["方向"] == "不适用" and k != "技-11":
                    errs.append(f"{name}/{k} 是乙类但方向写「不适用」")
    if errs:
        raise AssertionError("★★★ ②离场 / ⑤环境 三态表不完整:\n  - " + "\n  - ".join(errs))

    # 逐配置计数(方向按方法继承到它的每一份配置)
    out = {"②离场": {}, "⑤环境": {}}
    for axis, tbl in (("②离场", EXIT), ("⑤环境", REGIME)):
        cnt, dirs = {}, {}
        for k, cfgs in METHOD_OF.items():
            st = tbl[k]["态"]; dr = tbl[k]["方向"]
            cnt[st] = cnt.get(st, 0) + len(cfgs)
            if st == "乙":
                dirs[dr] = dirs.get(dr, 0) + len(cfgs)
        mt = MASTER_EXIT if axis == "②离场" else MASTER_REGIME
        for c, r in mt.items():
            cnt[r["态"]] = cnt.get(r["态"], 0) + 1
            if r["态"] == "乙":
                dirs[r["方向"]] = dirs.get(r["方向"], 0) + 1
        out[axis] = {"按配置计数": cnt, "乙类方向": dirs, "合计配置": sum(cnt.values())}
    out["配置总数(交易策略)"] = len(live)
    out["技-* 配置数"] = sum(len(v) for v in METHOD_OF.values())
    out["大师/锚点配置数"] = len(MASTER_EXIT)
    return out


if __name__ == "__main__":
    res = check_and_count()
    print("★ ②离场 / ⑤环境 三态表完整(配置目录全覆盖,无漏项)")
    print(json.dumps(res, ensure_ascii=False, indent=1))
    sys.exit(0)
